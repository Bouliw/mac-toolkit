// CleanLinks: strips tracking parameters from copied links (utm_*, fbclid, YouTube/Spotify ?si=…).
// Only touches a clipboard holding a single http(s) link, never passwords or plain text.
// Test without the clipboard: clean-links --test <url>…
import AppKit
import Foundation

let logFile = FileManager.default.homeDirectoryForCurrentUser
    .appendingPathComponent("Library/Logs/mac-toolkit/clean-links.log")
func log(_ message: String) {
    let f = DateFormatter(); f.dateFormat = "yyyy-MM-dd HH:mm:ss"
    let line = "\(f.string(from: Date())) \(message)\n"
    try? FileManager.default.createDirectory(at: logFile.deletingLastPathComponent(), withIntermediateDirectories: true)
    if let h = try? FileHandle(forWritingTo: logFile) { h.seekToEndOfFile(); h.write(line.data(using: .utf8)!); try? h.close() }
    else { try? line.write(to: logFile, atomically: true, encoding: .utf8) }
}

let everywhere: Set<String> = ["fbclid","gclid","dclid","gbraid","wbraid","msclkid","yclid","twclid","ttclid","li_fat_id",
    "mc_cid","mc_eid","igsh","igshid","_hsenc","_hsmi","mkt_tok","srsltid","oly_enc_id","oly_anon_id","vero_id",
    "wickedid","rb_clickid","s_cid","ref_src","ref_url","_ga","_gl","ncid","sr_share","cmpid","spm","scm","share_id"]
let perSite: [String: Set<String>] = [
    "youtube.com": ["si","pp","feature"], "youtu.be": ["si","feature"],
    "spotify.com": ["si","nd"], "x.com": ["s","t"], "twitter.com": ["s","t"],
    "linkedin.com": ["trk","trackingId","lipi","rcm","refId","midToken","midSig","trkEmail","eid","lici"],
    "reddit.com": ["rdt"], "facebook.com": ["mibextid","rdid","sfnsn"],
    "google.com": ["ved","ei","oq","gs_lcrp","sourceid","sclient","uact","iflsig","aqs","rlz","bih","biw","dpr","sca_esv","sca_upv","sa"],
    "amazon": ["ref","ref_","qid","sr","crid","sprefix","dib","dib_tag","content-id","_encoding","linkCode","linkId","tag","psc_ref","keywords"],
]
let dropWholeQuery: [String] = ["tiktok.com"]

func clean(_ s: String) -> String? {
    let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
    guard t.hasPrefix("http://") || t.hasPrefix("https://"), !t.contains(" "), !t.contains("\n"),
          var c = URLComponents(string: t), let host = c.host?.lowercased() else { return nil }
    let matches: (String) -> Bool = { d in host == d || host.hasSuffix("." + d) }
    var toRemove = everywhere
    for (d, params) in perSite where (d == "amazon" ? host.contains("amazon.") : matches(d)) { toRemove.formUnion(params) }
    var changed = false
    if dropWholeQuery.contains(where: matches), c.query != nil, c.path.contains("/video/") { c.queryItems = nil; changed = true }
    if let items = c.queryItems {
        let kept = items.filter { q in
            let lower = q.name.lowercased()
            if lower.hasPrefix("utm_") || lower.hasPrefix("pf_rd_") || lower.hasPrefix("pd_rd_") { return false }
            return !toRemove.contains(q.name) && !toRemove.contains(lower)
        }
        if kept.count != items.count { c.queryItems = kept.isEmpty ? nil : kept; changed = true }
    }
    if host.contains("amazon."), let r = c.path.range(of: "/ref=") { c.path = String(c.path[..<r.lowerBound]); changed = true }
    guard changed, let result = c.string, result != t else { return nil }
    return result
}

if CommandLine.arguments.count > 2, CommandLine.arguments[1] == "--test" {
    for u in CommandLine.arguments.dropFirst(2) { print(clean(u) ?? "(unchanged) \(u)") }
    exit(0)
}

let pasteboard = NSPasteboard.general
var lastChange = pasteboard.changeCount
let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
    let n = pasteboard.changeCount
    guard n != lastChange else { return }
    lastChange = n
    let types = Set((pasteboard.types ?? []).map { $0.rawValue })
    guard types.isDisjoint(with: ignoredTypes), !types.contains("public.file-url"),
          let s = pasteboard.string(forType: .string), let cleaned = clean(s) else { return }
    pasteboard.clearContents()
    pasteboard.setString(cleaned, forType: .string)
    pasteboard.setString(cleaned, forType: .URL)
    lastChange = pasteboard.changeCount
    log("link cleaned (\(URLComponents(string: cleaned)?.host ?? "?"))")
}
RunLoop.main.run()
